#!/usr/bin/env node

/**
 * stage-local-draft.js — Write a draft comment as a local Markdown fragment.
 *
 * Usage:
 *   echo '{"tool":"jira","target":"SITES-38280","url":"https://...","title":"...","context":"...","draft":"..."}' | node scripts/stage-local-draft.js
 *
 * Reads a JSON object from stdin with:
 *   - tool:     Source tool (jira, confluence, github)
 *   - target:   Target identifier (ticket key, page ID, issue number)
 *   - url:      Link to the original item
 *   - title:    Title of the ticket/page/issue
 *   - context:  One-line summary of what prompted this draft
 *   - draft:    The draft comment text (plain text or markdown)
 *
 * Writes a markdown file to {vault_path}/drafts/ with frontmatter and draft text.
 * Returns JSON envelope with the file path on success.
 *
 * Requires: VAULT_PATH env var or --vault CLI arg.
 *
 * Standalone: echo '{"tool":"jira","target":"TEST-1","draft":"test"}' | node scripts/stage-local-draft.js --vault /tmp
 * Reference:  docs/decisions/ADR-002-draft-generation-and-delivery.md
 */

import dotenv from 'dotenv'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeFile, mkdir } from 'node:fs/promises'
import { envelope } from './lib/config.js'

dotenv.config({ path: join(dirname(fileURLToPath(import.meta.url)), '.env') })

const TOOL = 'local_draft'

/**
 * Read all of stdin as a string.
 * @returns {Promise<string>}
 */
async function readStdin() {
  const chunks = []
  for await (const chunk of process.stdin) {
    chunks.push(chunk)
  }
  return Buffer.concat(chunks).toString('utf-8')
}

/**
 * Get the vault path from CLI args or env.
 * @returns {string|null}
 */
function getVaultPath() {
  const args = process.argv.slice(2)
  const idx = args.indexOf('--vault')
  if (idx !== -1 && args[idx + 1]) return args[idx + 1]
  return process.env.VAULT_PATH || null
}

/**
 * Sanitize a string for use in a filename.
 * @param {string} str
 * @returns {string}
 */
function sanitizeFilename(str) {
  return str.replace(/[^a-zA-Z0-9_-]/g, '-').replace(/-+/g, '-').slice(0, 80)
}

async function main() {
  const vaultPath = getVaultPath()
  if (!vaultPath) {
    console.log(JSON.stringify(envelope(TOOL, 'draft', null, [
      'VAULT_PATH not set — set env var or pass --vault /path/to/vault'
    ])))
    return
  }

  // Read draft input from stdin
  let input
  try {
    const raw = await readStdin()
    input = JSON.parse(raw)
  } catch (err) {
    console.log(JSON.stringify(envelope(TOOL, 'draft', null, [
      `Invalid JSON on stdin: ${err.message}. Expected: {"tool":"jira","target":"KEY-123","url":"...","title":"...","context":"...","draft":"..."}`
    ])))
    return
  }

  if (!input.draft) {
    console.log(JSON.stringify(envelope(TOOL, 'draft', null, ['Missing "draft" field in input'])))
    return
  }
  if (!input.tool) {
    console.log(JSON.stringify(envelope(TOOL, 'draft', null, ['Missing "tool" field in input'])))
    return
  }
  if (!input.target) {
    console.log(JSON.stringify(envelope(TOOL, 'draft', null, ['Missing "target" field in input'])))
    return
  }

  const today = new Date().toISOString().slice(0, 10)
  const safeTool = sanitizeFilename(input.tool)
  const safeTarget = sanitizeFilename(input.target)
  const filename = `${today}-${safeTool}-${safeTarget}-comment.md`
  const draftsDir = join(vaultPath, 'drafts')

  try {
    await mkdir(draftsDir, { recursive: true })

    // Build the markdown content
    const parts = []
    parts.push(`# Draft: ${input.tool.toUpperCase()} ${input.target} comment`)
    parts.push(`**Target:** [${input.target}](${input.url || '#'}) — ${input.title || 'Untitled'}`)
    parts.push(`**Context:** ${input.context || 'Draft generated by Morning Assistant'}`)
    parts.push(`**Date:** ${today}`)
    parts.push('')
    parts.push('---')
    parts.push('')
    parts.push(input.draft)
    parts.push('')

    const content = parts.join('\n')
    const filePath = join(draftsDir, filename)

    await writeFile(filePath, content, 'utf-8')

    console.log(JSON.stringify(envelope(TOOL, 'draft', {
      written: true,
      filePath,
      filename,
      tool: input.tool,
      target: input.target,
      url: input.url || null
    })))
  } catch (err) {
    console.error(`[${TOOL}]`, err.message)
    console.log(JSON.stringify(envelope(TOOL, 'draft', null, [err.message])))
  }
}

main()
